// Feature `TEXT` consts (`.claude/rules/02-text-and-types.md`) import from this instead of
// retyping a dotted path, so a typo is a compile error, not a silently-missing translation:
//
//   import { I18N_KEYS } from '@/i18n';
//   const TEXT = { save: I18N_KEYS.common.save } as const;
//
// This module is itself the reference implementation `pnpm i18n:check` measures every other
// key's usage against — until screens exist under `app/` and `features/`, it is also the
// only real consumer of most of these keys (docs/DECISIONS.md, 2026-09-04).

